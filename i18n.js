// ── LANGUAGE DETECTION & APPLICATION ────────────────

const BB_SUPPORTED = ['tr','de','en','fr','nl'];
const BB_STORAGE_KEY = 'bb_language';

function bb_detectLanguage() {
  // 1. Check saved preference (user manually switched)
  const saved = localStorage.getItem(BB_STORAGE_KEY);
  if (saved && BB_SUPPORTED.includes(saved)) return saved;

  // 2. Default is always Turkish — user can switch manually
  return 'tr';
}

function bb_setLanguage(lang) {
  if (!BB_SUPPORTED.includes(lang)) return;
  localStorage.setItem(BB_STORAGE_KEY, lang);
  // Reload the page — cleanest way to apply all translations including
  // hardcoded text that isn't using data-i18n attributes
  window.location.reload();
}

function bb_applyLanguage(lang) {
  const t = BB_TRANSLATIONS[lang] || BB_TRANSLATIONS['en'];

  // Apply all data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t[key];
      } else {
        el.textContent = t[key];
      }
    }
  });

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Update active flag buttons
  document.querySelectorAll('.bb-lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Update globe trigger label
  var label = document.getElementById('bb-lang-label');
  if (label) label.textContent = lang.toUpperCase();

  // Update active state in dropdown
  document.querySelectorAll('.bb-lang-option').forEach(function(btn) {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Store globally
  window.BB_LANG = lang;
  window.BB_T = t;
}

